-- 第 22 章：第三方登录。一个用户可以绑定多个服务商
CREATE TABLE oauth_identities (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider         VARCHAR(32)  NOT NULL,
    provider_user_id VARCHAR(128) NOT NULL,
    linked_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- 同一个服务商的同一个账号只能绑一次。
-- 这条唯一约束是防「账号接管」的最后一道防线。
CREATE UNIQUE INDEX ix_oauth_provider_user
    ON oauth_identities (provider, provider_user_id);

CREATE INDEX ix_oauth_user ON oauth_identities (user_id);
