CREATE TABLE posts (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body      TEXT         NOT NULL,
    body_html TEXT,
    timestamp TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    author_id BIGINT       NOT NULL REFERENCES users (id)
);

-- 首页按时间倒序列全部文章 → 这个索引是必须的
CREATE INDEX ix_posts_timestamp ON posts (timestamp DESC);
-- 资料页按作者 + 时间查 → 复合索引
CREATE INDEX ix_posts_author_timestamp ON posts (author_id, timestamp DESC);
